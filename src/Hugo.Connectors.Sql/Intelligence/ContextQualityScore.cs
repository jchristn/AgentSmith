namespace Hugo.Connectors.Sql.Intelligence
{
    using System;
    using System.Collections.Generic;

    /// <summary>
    /// A 0 to 100 score describing how ready the durable context is for agents, with the gaps that lower it.
    /// Not thread-safe for mutation.
    /// </summary>
    public class ContextQualityScore
    {
        #region Public-Members

        /// <summary>
        /// Score from 0 to 100.
        /// </summary>
        public int Score { get; set; } = 0;

        /// <summary>
        /// Label: <c>Strong</c> (85 and up), <c>Good</c> (65 and up), <c>Needs context</c> (40 and up), or
        /// <c>Degraded</c>.
        /// </summary>
        public string Label { get; set; } = "Degraded";

        /// <summary>
        /// Whether database-level context exists.
        /// </summary>
        public bool HasDatabaseContext { get; set; } = false;

        /// <summary>
        /// Tables with durable context.
        /// </summary>
        public int TablesWithContext { get; set; } = 0;

        /// <summary>
        /// Tables whose context was generated by a model and not since edited by an operator or agent.
        /// </summary>
        public int TablesWithGeneratedContext { get; set; } = 0;

        /// <summary>
        /// Tables and views crawled.
        /// </summary>
        public int TotalTables { get; set; } = 0;

        /// <summary>
        /// Declared foreign key edges.
        /// </summary>
        public int DeclaredRelationships { get; set; } = 0;

        /// <summary>
        /// Inferred relationship candidates.
        /// </summary>
        public int InferredRelationships { get; set; } = 0;

        /// <summary>
        /// Gaps and notes. Never null.
        /// </summary>
        public List<ContextQualitySignal> Signals
        {
            get
            {
                return _Signals;
            }
            set
            {
                _Signals = value ?? new List<ContextQualitySignal>();
            }
        }

        #endregion

        #region Private-Members

        private List<ContextQualitySignal> _Signals = new List<ContextQualitySignal>();

        #endregion

        #region Constructors-and-Factories

        /// <summary>
        /// Instantiate.
        /// </summary>
        public ContextQualityScore()
        {
        }

        #endregion
    }
}
