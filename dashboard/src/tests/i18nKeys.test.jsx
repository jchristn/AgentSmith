// Catalog completeness: every key the UI asks for exists in English, and every translated locale mirrors English
// exactly (same keys, same placeholders, no empty strings, no leftover English beyond product terms).

import { describe, it, expect } from 'vitest';
import fs from 'fs';
import path from 'path';
import { en, TRANSLATIONS } from '../i18n/resources';
import { LOCALES } from '../i18n/localeRegistry';
import { UNTRANSLATED_ALLOWLIST, isProductTerm } from './untranslatedAllowlist';
import resources from '../i18n/resources';
import * as resourceConfigs from '../views/resourceConfigs';
import * as hugoConfigs from '../views/hugoConfigs';
import { NAV_SECTIONS, HUBS, PAGES } from '../config/navConfig';
import { ENUMS, CHAT_EVENTS } from '../utils/constants';
import { SECRET_FIELD_NAMES } from '../utils/secrets';
import { TOUR_STEPS } from '../components/Tour';
import { WIZARD_STEPS } from '../components/SetupWizard';

const SRC = path.resolve(__dirname, '..');
const PLURAL = /_(zero|one|two|few|many|other)$/;

function leafKeys(node, prefix = '', out = new Set()) {
  for (const [k, v] of Object.entries(node || {})) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object') leafKeys(v, key, out);
    else out.add(key);
  }
  return out;
}

function lookup(catalog, key) {
  return key.split('.').reduce((n, part) => (n && typeof n === 'object' ? n[part] : undefined), catalog);
}

function exists(catalog, key) {
  if (typeof lookup(catalog, key) === 'string') return true;
  return typeof lookup(catalog, `${key}_one`) === 'string' || typeof lookup(catalog, `${key}_other`) === 'string';
}

function sourceFiles(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'tests' || entry.name === 'locales') continue;
      sourceFiles(full, out);
    } else if (/\.(js|jsx)$/.test(entry.name)) out.push(full);
  }
  return out;
}

/** A t() stand-in that records requested keys, skipping ones that carry a defaultValue. */
function recorder() {
  const keys = new Set();
  const t = (key, opts) => {
    if (!(opts && Object.prototype.hasOwnProperty.call(opts, 'defaultValue'))) keys.add(key);
    return key;
  };
  return { t, keys };
}

const CONFIGS = [...Object.values(resourceConfigs), ...Object.values(hugoConfigs)].filter((c) => c && typeof c === 'object' && c.id && c.columns);

describe('i18n key coverage', () => {
  it('has every static t() key used in source', () => {
    const missing = [];
    const re = /\bt\(\s*'([A-Za-z0-9_.]+)'\s*(,\s*\{\s*defaultValue)?/g;
    for (const file of sourceFiles(SRC)) {
      const text = fs.readFileSync(file, 'utf8');
      let m;
      while ((m = re.exec(text))) {
        if (m[2] || !m[1].includes('.')) continue;
        if (!exists(en, m[1])) missing.push(`${path.relative(SRC, file)}: ${m[1]}`);
      }
    }
    expect(missing).toEqual([]);
  });

  it('has every key generated by record page configurations', () => {
    const { t, keys } = recorder();
    const ctx = { t, i18n: { language: 'en' }, apiClient: {}, tenantId: 'default', principal: { isAdmin: true }, navigate: () => {}, addToast: () => {}, reload: () => {}, setExtraModal: () => {}, setJsonValue: () => {} };
    expect(CONFIGS.length).toBeGreaterThanOrEqual(18);
    for (const config of CONFIGS) {
      config.columns({ ...ctx, lookups: {} });
      const blank = config.blank ? config.blank(ctx) : {};
      for (const mode of ['create', 'edit', 'view']) if (config.fields) config.fields(blank, { ...ctx, mode, options: {} });
      for (const f of config.filters || []) if (typeof f.label === 'function') f.label(t);
      for (const k of ['title', 'subtitle', 'add', 'create', 'edit', 'view', 'deleteTitle', 'emptyTitle', 'emptyBody']) keys.add(`resources.${config.id}.${k}`);
      if (config.endpoint && config.id !== 'tenants') keys.add(`resources.${config.id}.title`);
      if (config.rowActions) config.rowActions({ id: 'x', name: 'x', status: 'Pending', enabled: true, toolInvocationId: 'tin_1' }, ctx);
    }
    const missing = [...keys].filter((k) => k.includes('.') && !exists(en, k));
    expect(missing).toEqual([]);
  });

  it('explains every Hugo page whose route may be missing on the server', () => {
    for (const id of ['profiles', 'approvals', 'conversations', 'resources', 'secrets', 'models', 'knowledge', 'toolInvocations', 'sessions', 'plugins']) {
      expect(exists(en, `resources.${id}.purpose`), id).toBe(true);
    }
  });

  it('has navigation labels and tips for every section, hub, and page', () => {
    for (const section of NAV_SECTIONS) expect(exists(en, `nav.sections.${section.key}`), section.key).toBe(true);
    for (const hub of HUBS) {
      expect(exists(en, `nav.hubs.${hub.key}.label`), hub.key).toBe(true);
      expect(exists(en, `tips.nav.hubs.${hub.key}`), hub.key).toBe(true);
    }
    for (const page of PAGES) expect(exists(en, `nav.items.${page.id}.label`), page.id).toBe(true);
  });

  it('has labels for every enum value (raw enum values are never shown)', () => {
    const missing = [];
    for (const [group, values] of Object.entries(ENUMS)) for (const v of values) if (!exists(en, `enums.${group}.${v}`)) missing.push(`${group}.${v}`);
    expect(missing).toEqual([]);
  });

  it('has labels for every secret field, tour stop, and wizard step', () => {
    for (const f of SECRET_FIELD_NAMES) {
      expect(exists(en, `components.secretField.fields.${f}`), f).toBe(true);
      expect(exists(en, `tips.secretField.fields.${f}`), f).toBe(true);
    }
    for (const s of TOUR_STEPS) expect(exists(en, `tour.steps.${s.id}.title`), s.id).toBe(true);
    for (const s of WIZARD_STEPS) expect(exists(en, `wizard.steps.${s}`) && exists(en, `wizard.bodies.${s}`), s).toBe(true);
    expect(CHAT_EVENTS).toContain('approval.required');
  });

  it('keeps acronyms upper case in every catalog', () => {
    const acronym = /(?<![\w./{-])(mcp|a2a|api|apis|url|urls|json|sse|http|https|sdk|Mcp|Api|Url|Json|Sse|Http)(?![\w/.}:-])/;
    const offenders = [];
    for (const [code, catalog] of [['en', en], ...Object.entries(TRANSLATIONS)]) {
      for (const key of leafKeys(catalog)) if (acronym.test(String(lookup(catalog, key)))) offenders.push(`${code}: ${key}`);
    }
    expect(offenders).toEqual([]);
  });
});

describe('locale parity', () => {
  const base = (keys) => new Set([...keys].map((k) => k.replace(PLURAL, '')));
  const enKeys = base(leafKeys(en));
  const locales = Object.entries(TRANSLATIONS);

  it('covers every real locale in the registry', () => {
    const real = LOCALES.filter((l) => l.code !== 'en' && !l.pseudo).map((l) => l.code);
    expect(Object.keys(TRANSLATIONS).sort()).toEqual(real.sort());
  });

  it.each(locales)('%s has exactly the English keys', (_code, catalog) => {
    const keys = base(leafKeys(catalog));
    expect([...enKeys].filter((k) => !keys.has(k))).toEqual([]);
    expect([...keys].filter((k) => !enKeys.has(k))).toEqual([]);
  });

  it.each(locales)('%s keeps every interpolation placeholder', (_code, catalog) => {
    const vars = (s) => (String(s).match(/\{\{\s*([A-Za-z0-9_.]+)\s*\}\}/g) || []).map((v) => v.replace(/[{}\s]/g, '')).sort();
    const mismatched = [];
    for (const key of leafKeys(catalog)) {
      const target = lookup(catalog, key);
      const source = lookup(en, key) ?? lookup(en, key.replace(PLURAL, '_other'));
      if (typeof source !== 'string') continue;
      const expected = vars(source).filter((v) => v !== 'count' || /\{\{\s*count/.test(target));
      if (JSON.stringify([...new Set(vars(target))]) !== JSON.stringify([...new Set(expected)])) mismatched.push(key);
    }
    expect(mismatched).toEqual([]);
  });

  it.each(locales)('%s has no empty or non-string values', (_code, catalog) => {
    const bad = [...leafKeys(catalog)].filter((k) => {
      const v = lookup(catalog, k);
      return typeof v !== 'string' || v.trim() === '';
    });
    expect(bad).toEqual([]);
  });

  it.each(locales)('%s leaves little English copy behind beyond product terms and the allowlist', (code, catalog) => {
    const allowed = new Set([...(UNTRANSLATED_ALLOWLIST['*'] || []), ...(UNTRANSLATED_ALLOWLIST[code] || [])]);
    const leftovers = [];
    for (const key of leafKeys(catalog)) {
      const target = lookup(catalog, key);
      const source = lookup(en, key) ?? lookup(en, key.replace(PLURAL, '_other'));
      if (target !== source) continue;
      if (isProductTerm(target) || allowed.has(target)) continue;
      // Short labels are often spelled the same (Status, Name); longer sentences are not.
      if (target.split(/\s+/).length <= 3) continue;
      leftovers.push(`${key}: ${target}`);
    }
    expect(leftovers).toEqual([]);
  });

  it('contains no em-dashes or en-dashes in any catalog', () => {
    for (const [code, catalog] of [['en', en], ...locales]) {
      expect(JSON.stringify(catalog), code).not.toContain(String.fromCharCode(0x2014));
      expect(JSON.stringify(catalog), code).not.toContain(String.fromCharCode(0x2013));
    }
  });

  it('generates complete pseudo-locales that preserve placeholders', () => {
    for (const code of ['en-XA', 'ar-XB']) {
      const catalog = resources[code].translation;
      expect(leafKeys(catalog).size).toBe(leafKeys(en).size);
      expect(lookup(catalog, 'common.errors.requestId')).toContain('{{id}}');
    }
  });
});
