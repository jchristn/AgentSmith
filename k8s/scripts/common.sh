#!/usr/bin/env bash
# Shared helpers for the Hugo Kubernetes scripts. Sourced, not executed.
#
# Environment understood by every script:
#   HUGO_KUBE_CONTEXT   kubectl context to use (default: the current context). The minikube scripts set it to the
#                       minikube profile, so they never depend on or change your current context.
#   HUGO_TAG            image tag for hugo-server and hugo-dashboard (default v0.1.0, the tag in k8s/base)
set -euo pipefail

# The manifests use namespace hugo, and the dashboard's upstream URL names it (hugo-server.hugo.svc.cluster.local).
HUGO_NAMESPACE="hugo"
HUGO_TAG="${HUGO_TAG:-v0.1.0}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
K8S_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
REPO_DIR="$(cd "${K8S_DIR}/.." && pwd)"
HUGO_IMAGES="jchristn77/hugo-server jchristn77/hugo-dashboard"

log() { printf '[hugo] %s\n' "$*"; }
fail() { printf '[hugo] error: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || fail "$1 is required but was not found on PATH"; }

# kubectl in the chosen context, always in the hugo namespace.
kc() {
  if [ -n "${HUGO_KUBE_CONTEXT:-}" ]; then
    kubectl --context "${HUGO_KUBE_CONTEXT}" -n "${HUGO_NAMESPACE}" "$@"
  else
    kubectl -n "${HUGO_NAMESPACE}" "$@"
  fi
}

# kubectl in the chosen context without a namespace (cluster-scoped objects).
kcc() {
  if [ -n "${HUGO_KUBE_CONTEXT:-}" ]; then
    kubectl --context "${HUGO_KUBE_CONTEXT}" "$@"
  else
    kubectl "$@"
  fi
}

# Starts kubectl port-forward in the background and appends its PID to PIDS. kubectl itself is backgrounded (not a
# shell function wrapping it), so killing the PID really stops the forward.
PIDS=""
start_forward() {
  if [ -n "${HUGO_KUBE_CONTEXT:-}" ]; then
    kubectl --context "${HUGO_KUBE_CONTEXT}" -n "${HUGO_NAMESPACE}" port-forward --address 127.0.0.1 "$@" >/dev/null 2>&1 &
  else
    kubectl -n "${HUGO_NAMESPACE}" port-forward --address 127.0.0.1 "$@" >/dev/null 2>&1 &
  fi
  PIDS="${PIDS} $!"
}

context_name() {
  if [ -n "${HUGO_KUBE_CONTEXT:-}" ]; then printf '%s' "${HUGO_KUBE_CONTEXT}"; else kubectl config current-context 2>/dev/null || printf '(none)'; fi
}

# Maps a target name to its overlay directory, relative to the repository root.
target_dir() {
  case "$1" in
    k3s) printf 'k8s/overlays/k3s' ;;
    production) printf 'k8s/overlays/production' ;;
    minikube) printf 'minikube/overlay' ;;
    *) fail "unknown target $1 (use k3s, production, or minikube)" ;;
  esac
}

# Validates a comma-separated component list (postgres, observability, or empty).
check_components() {
  local c
  for c in $(printf '%s' "$1" | tr ',' ' '); do
    [ -d "${K8S_DIR}/components/${c}" ] && [ "${c}" != "ingress" ] || fail "unknown component ${c} (use postgres and/or observability)"
  done
}

# Writes k8s/.work/deploy/kustomization.yaml: the target overlay plus the chosen components, with the image tag
# HUGO_TAG. Prints the directory. Kustomize allows components from outside the kustomization root, so the overlays
# stay unchanged.
render_dir() {
  local target="$1" components="$2" dir="${K8S_DIR}/.work/deploy" c
  mkdir -p "${dir}"
  {
    echo "# Generated by k8s/scripts; do not edit. Target $1, components: ${components:-none}."
    echo "apiVersion: kustomize.config.k8s.io/v1beta1"
    echo "kind: Kustomization"
    echo "namespace: ${HUGO_NAMESPACE}"
    echo "resources:"
    echo "  - ../../../$(target_dir "${target}")"
    if [ -n "${components}" ]; then
      echo "components:"
      for c in $(printf '%s' "${components}" | tr ',' ' '); do echo "  - ../../components/${c}"; done
    fi
    echo "images:"
    for image in ${HUGO_IMAGES}; do
      echo "  - name: ${image}"
      echo "    newTag: ${HUGO_TAG}"
    done
  } > "${dir}/kustomization.yaml"
  printf '%s' "${dir}"
}

# Applies a target with components and records both on the namespace, so update.sh and factory-reset.sh can
# re-apply the same shape without being told again.
apply_target() {
  local target="$1" components="$2" dir
  dir="$(render_dir "${target}" "${components}")"
  log "applying $(target_dir "${target}")${components:+ with ${components}} (tag ${HUGO_TAG}) to context $(context_name)"
  if [ -n "${HUGO_KUBE_CONTEXT:-}" ]; then
    kubectl --context "${HUGO_KUBE_CONTEXT}" apply -k "${dir}"
  else
    kubectl apply -k "${dir}"
  fi
  kcc annotate namespace "${HUGO_NAMESPACE}" --overwrite \
    "hugo-deploy-target=${target}" "hugo-deploy-components=${components}" >/dev/null
}

# Reads the target and components recorded by apply_target. Prints "target components" or nothing.
recorded_shape() {
  local t c
  t="$(kcc get namespace "${HUGO_NAMESPACE}" -o jsonpath='{.metadata.annotations.hugo-deploy-target}' 2>/dev/null || true)"
  c="$(kcc get namespace "${HUGO_NAMESPACE}" -o jsonpath='{.metadata.annotations.hugo-deploy-components}' 2>/dev/null || true)"
  [ -n "${t}" ] && printf '%s %s' "${t}" "${c}"
  return 0
}

# Waits for PostgreSQL (when deployed), the server, the dashboard, and the observability stack (when deployed).
wait_for_rollout() {
  log "waiting for rollout"
  if kc get statefulset hugo-postgres >/dev/null 2>&1; then
    kc rollout status statefulset/hugo-postgres --timeout=300s
  fi
  kc rollout status deployment/hugo-server --timeout=600s
  kc rollout status deployment/hugo-dashboard --timeout=300s
  if kc get deployment hugo-grafana >/dev/null 2>&1; then
    local name
    for name in hugo-prometheus hugo-loki hugo-tempo hugo-alloy hugo-grafana; do
      kc rollout status "deployment/${name}" --timeout=600s
    done
  fi
}

# Prints how to reach the stack after a deploy.
print_access() {
  log "reach it with k8s/scripts/port-forward.sh (minikube: minikube/scripts/port-forward.sh):"
  log "  dashboard http://127.0.0.1:8801   REST, MCP (/mcp), and A2A http://127.0.0.1:8800"
  if kc get service hugo-grafana >/dev/null 2>&1; then
    log "  Grafana http://127.0.0.1:3000 (user admin; password: kubectl -n ${HUGO_NAMESPACE} get secret hugo-secrets -o jsonpath='{.data.grafana-admin-password}' | base64 --decode)"
  fi
  log "sign in to tenant default as anderson@hugo.local or admin@hugo.local with password 'password'; the dashboard prompts you to change it"
}

# Parses "--with a,b" style options shared by deploy, update, and factory-reset into WITH (and WITH_SET=1).
WITH=""
WITH_SET=0
parse_with() {
  case "$1" in
    --with) WITH="$2"; WITH_SET=1; return 0 ;;
    --with=*) WITH="${1#--with=}"; WITH_SET=1; return 0 ;;
  esac
  return 1
}
